import type { ShellBlock as Block, Issue, ShellGenerator } from './types';
import { appName } from '../../consts';

const keyPattern = /^[a-zA-Z_][a-zA-Z0-9_]*$/;

export function validateBlocks(blocks: Block[]): Issue[] {
  const issues: Issue[] = [];
  const keys = new Set<string>();
  for (const block of blocks) {
    if (block.kind === 'env') {
      for (const variable of block.variables) {
        if (!variable.key.trim()) {
          issues.push({ level: 'error', block: block.name, message: 'Key 不能为空' });
        }
        if (variable.key === 'HOME') {
          issues.push({
            level: 'error',
            block: block.name,
            message: 'HOME 是内置变量，不能作为 Key；请使用 ${HOME} 引用系统主目录',
          });
        }
      }
    }
    if (!block.enabled) {
      continue;
    }
    if (!block.name.trim()) {
      issues.push({ level: 'warning', block: block.name, message: '块名称为空' });
    }
    if (block.kind === 'shell') {
      if (!['both', 'bash', 'zsh'].includes(block.shell)) {
        issues.push({
          level: 'error',
          block: block.name,
          message: `Bash / Zsh 生成器不支持脚本范围：${block.shell}`,
        });
      }
      if (!block.script.trim()) {
        issues.push({ level: 'warning', block: block.name, message: 'Shell 脚本为空' });
      }
      continue;
    }
    for (const v of block.variables.filter((v) => v.enabled)) {
      const add = (level: Issue['level'], message: string) => issues.push({ level, block: block.name, message });
      if (v.key && !keyPattern.test(v.key)) {
        add('error', `非法 Key：${v.key}`);
      }
      if (v.key === 'PATH' || v.key.startsWith('_environment_manager_')) {
        add('error', `${v.key} 是保留变量；请使用“加入 PATH”`);
      }
      if (v.key && keys.has(v.key)) {
        add('error', `重复 Key：${v.key}`);
      }
      if (v.key) {
        keys.add(v.key);
      }
      if (!v.value.trim()) {
        add(v.addToPath ? 'error' : 'warning', `${v.key || 'PATH'} 的 Value 为空`);
      }
      if (v.value.includes('\0')) {
        add('error', `${v.key || 'PATH'} 包含 NUL 字符`);
      }
      if (v.addToPath && /[:\r\n]/.test(v.value)) {
        add('error', 'PATH 每项只能包含一个目录，不能含冒号或换行');
      }
    }
  }
  return issues;
}

// 引用统一生成 ${KEY}，兼容已有配置中的 $KEY；其他 Shell 语法按字面量保存。
function shellValueContent(value: string): string {
  const input = value.replace(/^~(?=\/|$)/, '${HOME}');
  let result = '';
  for (let i = 0; i < input.length;) {
    const char = input[i]!;
    if (char === '$') {
      const match = input.slice(i).match(/^\$(?:\{([a-zA-Z_][a-zA-Z0-9_]*)\}|([a-zA-Z_][a-zA-Z0-9_]*))/);
      if (match) {
        result += '${' + (match[1] ?? match[2]) + '}';
        i += match[0].length;
        continue;
      }
      result += '\\$';
    } else {
      result += /["\\`]/.test(char) ? `\\${char}` : char;
    }
    i++;
  }
  return result;
}
export function shellValue(value: string): string {
  return `"${shellValueContent(value)}"`;
}
export const shellLiteral = (value: string) => `'${value.replaceAll("'", "'\\''")}'`;

export function pathEntries(blocks: Block[]): { block: string; value: string }[] {
  const seen = new Set<string>();
  return blocks
    .filter((b) => b.enabled && b.kind === 'env')
    .flatMap((b) =>
      b.variables
        .filter((v) => v.enabled && v.addToPath && v.value.trim())
        .flatMap((v) => {
          if (seen.has(v.value)) {
            return [];
          }
          seen.add(v.value);
          return [{ block: b.name, value: v.value }];
        }),
    );
}

export function generateProfile(blocks: Block[]): string {
  const errors = validateBlocks(blocks).filter((i) => i.level === 'error');
  if (errors.length) {
    throw new Error(errors.map((i) => `${i.block}：${i.message}`).join('\n'));
  }
  const lines = [
    `# Generated by ${appName}. Edit your configuration in ${appName}.`,
    '# Compatible with Bash / Zsh.',
    '',
  ];
  // 先按块顺序写入变量和脚本，最后将管理的目录放到现有 PATH 前面。
  for (const b of blocks.filter((b) => b.enabled)) {
    lines.push(`# ${b.name.replace(/[\r\n]/g, ' ')}`);
    if (b.kind === 'env') {
      for (const v of b.variables.filter((v) => v.enabled && v.key)) {
        if (v.description) {
          lines.push(`# ${v.description.replace(/[\r\n]/g, ' ')}`);
        }
        lines.push(`export ${v.key}=${shellValue(v.value)}`);
      }
    } else if (b.script.trim()) {
      if (b.shell !== 'both') {
        lines.push(`if [ -n "\${${b.shell === 'bash' ? 'BASH' : 'ZSH'}_VERSION-}" ]; then`);
      }
      lines.push(b.script);
      if (b.shell !== 'both') {
        lines.push('fi');
      }
    }
    lines.push('');
  }
  const paths = pathEntries(blocks);
  if (paths.length) {
    lines.push(`export PATH="${paths.map(({ value }) => shellValueContent(value)).join(':')}\${PATH:+:$PATH}"`, '');
  }
  return lines.join('\n');
}

const start = `# >>> ${appName} >>>`;
const end = `# <<< ${appName} <<<`;
export function rcRegion(content: string): { from: number; to: number } | null {
  const starts = [...content.matchAll(new RegExp(`^# >>> ${appName} >>>\\r?$`, 'gm'))];
  const ends = [...content.matchAll(new RegExp(`^# <<< ${appName} <<<\\r?$`, 'gm'))];
  if (!starts.length && !ends.length) {
    return null;
  }
  if (starts.length !== 1 || ends.length !== 1 || starts[0]!.index! >= ends[0]!.index!) {
    throw new Error('环境变量管理器 标记不完整或重复，请先修复文件中的标记');
  }
  const finish = ends[0]!.index! + ends[0]![0].length;
  return { from: starts[0]!.index!, to: content[finish] === '\n' ? finish + 1 : finish };
}
export function updateRc(content: string, profilePath: string, remove = false): string {
  const region = rcRegion(content);
  const newline = content.includes('\r\n') ? '\r\n' : '\n';
  const quoted = shellLiteral(profilePath);
  const section = [start, `[ -f ${quoted} ] && . ${quoted}`, end, ''].join(newline);
  if (region) {
    return content.slice(0, region.from) + (remove ? '' : section) + content.slice(region.to);
  }
  if (remove) {
    return content;
  }
  return content + (content && !content.endsWith('\n') ? newline : '') + section;
}

export function resolveVariables(value: string, variables: Record<string, string>): string | null {
  let unresolved = false;
  const result = value
    .replace(/^~(?=\/|$)/, variables.HOME ?? '~')
    .replace(/\$\{([a-zA-Z_][a-zA-Z0-9_]*)\}|\$([a-zA-Z_][a-zA-Z0-9_]*)/g, (_, a: string, b: string) => {
      const key = a || b;
      if (!Object.hasOwn(variables, key)) {
        unresolved = true;
        return '';
      }
      return variables[key]!;
    });
  return unresolved ? null : result;
}

export const posixGenerator: ShellGenerator = {
  id: 'bash-zsh',
  label: 'Bash / Zsh',
  extension: 'sh',
  validate: validateBlocks,
  generate: generateProfile,
  paths: pathEntries,
  integrate: updateRc,
  isIntegrated: (content) => rcRegion(content) !== null,
  resolvePath: resolveVariables,
};
